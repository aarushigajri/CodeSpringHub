"""Create the SYNTHETIC demo dataset used to try the Hub (random numbers, not real biology)."""

import gzip
import random
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "demo_data" / "demo-rnaseq"
random.seed(42)
OUT.mkdir(parents=True, exist_ok=True)

samples = [f"S{i}" for i in range(1, 7)]
conditions = ["control"] * 3 + ["treated"] * 3

with open(OUT / "samplesheet.csv", "w") as fh:
    fh.write("sample,condition,replicate,fastq_1\n")
    for i, (s, c) in enumerate(zip(samples, conditions)):
        fh.write(f"{s},{c},{i % 3 + 1},reads/{s}_R1.fastq.gz\n")

with open(OUT / "counts.tsv", "w") as fh:
    fh.write("gene_id\t" + "\t".join(samples) + "\n")
    for g in range(1, 501):
        base = random.randint(0, 2000)
        fold = 3 if g <= 25 else 1  # first 25 genes "up" in treated
        row = [int(base * (fold if c == "treated" else 1) * random.uniform(0.8, 1.2)) for c in conditions]
        fh.write(f"GENE{g:04d}\t" + "\t".join(map(str, row)) + "\n")

(OUT / "reads").mkdir(exist_ok=True)
for s in samples[:2]:
    with gzip.open(OUT / "reads" / f"{s}_R1.fastq.gz", "wt") as fh:
        for r in range(500):
            seq = "".join(random.choice("ACGT") for _ in range(100))
            fh.write(f"@{s}.{r}\n{seq}\n+\n{'I' * 100}\n")

(OUT / "README.md").write_text("# Demo RNA-seq\n\nSYNTHETIC data generated by scripts/make_demo_data.py.\n")
print(f"wrote {OUT}")
